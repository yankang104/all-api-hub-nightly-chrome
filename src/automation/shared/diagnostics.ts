/**
 * 不参与判定的步骤 —— 它们描述**我们做了什么**，不是**站点出了什么问题**。
 *
 * 两类都必须排除，因为各自造成过一次真实误诊：
 *
 * 1. 开头的环境说明。「使用 Chrome/系统网络设置（扩展未覆盖代理）」同时含
 *    「网络」和「代理」，命中 NETWORK_FAILURE，而它的优先级高于
 *    SELECTOR_MISMATCH —— 于是**任何**失败都被报成「网络请求失败，
 *    检查代理节点」，真正的原因（找不到密码框）被完全盖掉。
 *
 * 2. 我们自己的处置动作。「已清除 4 项本地登录态」含「登录态」，命中
 *    AUTH_EXPIRED —— 于是失败被报成「登录状态已失效，重新签到即可」，
 *    而实际上重试一百次也一样，该改的是选择器。
 *
 * 判据是「这行话是不是站点告诉我们的」：不是的就不该拿来判断站点怎么了。
 */
/**
 * 纯否定式自述：否定词与验证对象之间只允许「任何 / 额外的」这类直接修饰。
 *
 * 「未发现异常，随后弹出安全验证」不会命中 —— 否定词与验证对象之间夹着整句话，
 * 那是先否定后肯定的句子，真实挑战必须参与判定。
 *
 * 行尾的负向断言是第二道闸：同一行里只要还写着正向证据，就不算纯否定。
 */
const NEGATED_CHALLENGE_REPORT = /(?:未|没有|未见|尚未|未曾|无)(?:发现|检测到|出现|需|需额外|检出|观察到)?(?:额外的?|任何)?(?:人机|安全|滑块|图形|行为|智能)?(?:验证|校验|验证码)(?:证据|要求)?(?!.*(?:检测到|出现|弹出|触发|提示|要求|需要|等待你|未完成|无法完成|失败|错误|超时|请完成|请先完成))/;

/** 「无需……」形态的否定自述（与上一条同源，只是「需」不能省略）。 */
const NEGATED_CHALLENGE_WITH_EXTRA_ONLY = /无(?:需|需额外)(?:额外的?|任何)?(?:人机|安全|滑块|图形|行为|智能)?(?:验证|校验|验证码)/;

